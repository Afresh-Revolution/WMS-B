function getRoleDefinition(role) {
  return ROLE_DEFINITIONS[role] || null;
}

function getRolePermissions(role) {
  const definition = getRoleDefinition(role);
  return definition ? definition.permissions : [];
}

function hasPermission(user, permission) {
  if (!user) {
    return false;
  }

  const rolePermissions = getRolePermissions(user.role);
  const directPermissions = Array.isArray(user.permissions) ? user.permissions : [];
  return rolePermissions.includes(permission) || directPermissions.includes(permission);
}

module.exports = { PERMISSIONS, ROLE_DEFINITIONS, getRoleDefinition, getRolePermissions, hasPermission };
