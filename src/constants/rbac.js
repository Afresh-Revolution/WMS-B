const PERMISSION_ACTIONS = ["view", "create", "update", "delete", "approve", "reject", "export", "manage", "configure"];

function buildEnterprisePermissions() {
  return ENTERPRISE_MODULE_KEYS.reduce((permissions, moduleKey) => {
    for (const action of PERMISSION_ACTIONS) {
      const key = `${moduleKey}.${action}`.toUpperCase().replace(/[^A-Z0-9]+/g, "_");
      permissions[key] = `${moduleKey}.${action}`;
    }

    return permissions;
  }, {});
}

